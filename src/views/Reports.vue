<script setup>
import { computed, onMounted, ref, watch } from 'vue'
import { useStore } from '../store/index.js'
import { useTableControls } from '../composables/useTableControls.js'
import { reportService } from '../services/reportService.js'

const { state, can, formatCurrency } = useStore()
const reportType = ref(state.currentUser.role === 'manager' ? 'projects' : 'attendance')
const canAccess = computed(() => can('Reports', 'view'))
const employeeFilter = ref('all')
const statusFilter = ref('all')
const dateFrom = ref('')
const dateTo = ref('')
const reportQuery = ref('')
const reportRows = ref([])
const reportColumns = ref([])
const reportTitle = ref('')
const isLoading = ref(false)
const loadError = ref('')

const reportOptions = computed(() => [
  { id: 'attendance', label: 'Attendance', module: 'Attendance', action: 'view' },
  { id: 'leaves', label: 'Leave Requests', module: 'Leave Request', action: 'approve' },
  { id: 'claims', label: 'Medical Claims', module: 'Medical Request', action: 'approve' },
  { id: 'employees', label: 'Employees', module: 'Employees', action: 'view' },
  { id: 'assets', label: 'Assets', module: 'Assets', action: 'view' },
  { id: 'policies', label: 'Policies', module: 'Company Hub', action: 'create' },
  { id: 'projects', label: 'Projects & Tickets', module: 'Projects', action: 'view' },
  { id: 'finance', label: 'Finance', module: 'Finance', action: 'finance' }
].filter(option => can(option.module, option.action)))

const filters = () => ({ employee: employeeFilter.value, status: statusFilter.value, dateFrom: dateFrom.value, dateTo: dateTo.value, query: reportQuery.value })
const reportEmployees = computed(() => Array.from(new Set(reportRows.value.map(row => row.employee || row.name || row.manager || row.assignedTo).filter(Boolean))).sort())
const reportStatuses = computed(() => Array.from(new Set(reportRows.value.map(row => row.status).filter(Boolean))).sort())
const reportTable = useTableControls(computed(() => reportRows.value), row => Object.values(row).join(' '), 25)
const reportCards = computed(() => [
  { label: 'Matching records', value: reportRows.value.length },
  { label: 'Columns', value: reportColumns.value.length },
  { label: 'Report', value: reportTitle.value || '—' }
])

async function loadReport() {
  if (!canAccess.value) return
  isLoading.value = true
  loadError.value = ''
  try {
    const report = await reportService.list(reportType.value, filters())
    reportRows.value = report.rows || []
    reportColumns.value = report.columns || Object.keys(reportRows.value[0] || {})
    reportTitle.value = report.title || `${reportType.value} report`
  } catch (error) {
    reportRows.value = []
    reportColumns.value = []
    loadError.value = error?.message || 'Unable to load this report.'
  } finally {
    isLoading.value = false
  }
}

async function exportCsv() {
  if (!reportRows.value.length) return
  try {
    await reportService.download(reportType.value, filters())
  } catch (error) {
    loadError.value = error?.message || 'Unable to export this report.'
  }
}

watch(reportOptions, options => {
  if (!options.some(option => option.id === reportType.value)) reportType.value = options[0]?.id || 'attendance'
}, { immediate: true })
watch(reportType, () => {
  employeeFilter.value = 'all'; statusFilter.value = 'all'; dateFrom.value = ''; dateTo.value = ''; reportQuery.value = ''
  loadReport()
})
onMounted(loadReport)
</script>

<template>
  <div v-if="canAccess" class="orbit-page space-y-6">
    <div class="orbit-page-header flex flex-col gap-4 lg:flex-row lg:items-end lg:justify-between">
      <div><div class="text-sm text-slate-600">Authoritative, permission-scoped operational reports and CSV exports.</div></div>
      <div class="flex gap-2"><select v-model="reportType" class="table-filter-input min-w-[220px]"><option v-for="option in reportOptions" :key="option.id" :value="option.id">{{ option.label }}</option></select><button type="button" :disabled="!reportRows.length" @click="exportCsv" class="orbit-button orbit-button-primary px-4 py-2 text-sm font-medium disabled:opacity-50">Export CSV</button></div>
    </div>
    <section class="grid grid-cols-1 gap-4 md:grid-cols-3"><div v-for="card in reportCards" :key="card.label" class="orbit-stat-card p-4"><div class="text-xs font-bold uppercase tracking-wide text-slate-500">{{ card.label }}</div><div class="mt-2 text-2xl font-extrabold text-slate-900">{{ card.value }}</div></div></section>
    <section class="orbit-table-card overflow-hidden"><div class="border-b border-slate-200 px-4 py-3"><div class="text-sm font-bold text-slate-900">{{ reportTitle }}</div><div class="mt-1 text-xs text-slate-600">Rows and exports are generated by the server using your current access scope.</div></div><div class="table-tools"><input v-model="reportQuery" type="search" placeholder="Search report..." class="table-filter-input" @keyup.enter="loadReport" /><select v-model="employeeFilter" class="table-filter-input max-w-[220px]"><option value="all">All people</option><option v-for="person in reportEmployees" :key="person" :value="person">{{ person }}</option></select><select v-model="statusFilter" class="table-filter-input max-w-[180px]"><option value="all">All statuses</option><option v-for="status in reportStatuses" :key="status" :value="status">{{ status }}</option></select><input v-model="dateFrom" type="date" class="table-filter-input max-w-[160px]" /><input v-model="dateTo" type="date" class="table-filter-input max-w-[160px]" /><button type="button" class="orbit-button orbit-button-secondary px-3 py-2 text-xs font-bold" :disabled="isLoading" @click="loadReport">{{ isLoading ? 'Loading…' : 'Apply filters' }}</button><div class="table-count">{{ reportRows.length }} records</div></div><div v-if="loadError" class="px-4 py-3 text-sm text-rose-600">{{ loadError }}</div><div class="table-scroll" @scroll="reportTable.loadMoreRows"><table class="orbit-data-table w-full text-sm"><thead><tr class="border-b border-slate-200 bg-slate-50/80 text-left"><th v-for="header in reportColumns" :key="header" class="px-4 py-3 text-xs font-medium uppercase tracking-wide text-slate-500">{{ header }}</th></tr></thead><tbody><tr v-for="(row, index) in reportTable.visibleRows.value" :key="index" class="border-b border-slate-200 last:border-0 hover:bg-slate-50/60"><td v-for="header in reportColumns" :key="header" class="px-4 py-3 text-slate-700">{{ ['budget', 'received', 'pending', 'commission', 'amount'].includes(header) ? formatCurrency(row[header]) : row[header] }}</td></tr><tr v-if="!isLoading && !reportRows.length"><td :colspan="reportColumns.length || 1" class="px-4 py-8 text-center text-sm text-slate-500">No report data available.</td></tr></tbody></table></div></section>
  </div>
  <div v-else class="rounded-xl border border-slate-200 bg-white p-6 shadow-sm"><div class="text-lg font-semibold text-slate-900">Reports are not available for this role</div></div>
</template>
